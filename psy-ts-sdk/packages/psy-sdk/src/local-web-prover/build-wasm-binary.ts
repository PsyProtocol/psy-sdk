import fs from "fs";
import path from "path";
import { spawnSync } from "child_process";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const wasmPath = path.join(__dirname, "./psy_prover_bg.wasm");

// Prover features per target. PSY_PROVER_FEATURES applies to both; `threads` and
// `threads-no-bundler` are web-only (Node has no Web Workers, and wasm-bindgen-rayon's helper
// touches `self` at import, which crashes Node).
function featuresFor(target: "web" | "nodejs"): string[] {
    const all = (process.env.PSY_PROVER_FEATURES ?? "")
        .split(/[\s,]+/)
        .filter((f) => f.length > 0);
    const webOnly = ["threads", "threads-no-bundler"];
    const features = target === "web" ? all : all.filter((f) => !webOnly.includes(f));
    return features.length > 0 ? ["--features", features.join(",")] : [];
}

// wasm-bindgen-rayon's worker helper assumes the consumer serves this package's files as they
// are: it spawns `new URL("./workerHelpers.js", import.meta.url)` and the worker imports the
// glue with `import("../../..")`. Neither survives the SDK's rollup build or a host bundler, and
// its top-level `self` listener breaks Node. Replace it with a helper that has no import-time
// side effects and spawns workers from a host-provided factory (setThreadWorkerFactory); the
// worker side is `startProverThreadWorker` in provider.ts.
const PATCHED_WORKER_HELPERS = `// Generated by build-wasm-binary.ts from wasm-bindgen-rayon's workerHelpers.js (Apache-2.0,
// Copyright 2022 Google Inc.): no import-time side effects, workers come from the host.
function waitForMsgType(target, type) {
  return new Promise(resolve => {
    target.addEventListener('message', function onMsg({ data }) {
      if (data?.type !== type) return;
      target.removeEventListener('message', onMsg);
      resolve(data);
    });
  });
}

// Keep the workers referenced (Firefox collects unrooted workers that share memory).
let _workers;

export async function startWorkers(module, memory, builder) {
  if (builder.numThreads() === 0) {
    throw new Error('num_threads must be > 0.');
  }
  const factory = globalThis.__psyProverThreadWorkerFactory;
  if (typeof factory !== 'function') {
    throw new Error('prover threads need a worker factory: call setThreadWorkerFactory()');
  }
  const workerInit = {
    type: 'wasm_bindgen_worker_init',
    init: { module_or_path: module, memory },
    receiver: builder.receiver()
  };
  _workers = await Promise.all(
    Array.from({ length: builder.numThreads() }, async () => {
      const worker = factory();
      worker.postMessage(workerInit);
      // A worker that fails to start must fail the pool, not hang it.
      const failed = new Promise((_, reject) => {
        worker.addEventListener('error', event => reject(new Error('prover thread failed: ' + (event.message || 'error'))));
        waitForMsgType(worker, 'wasm_bindgen_worker_error').then(({ error }) => reject(new Error('prover thread failed: ' + error)));
      });
      await Promise.race([waitForMsgType(worker, 'wasm_bindgen_worker_ready'), failed]);
      return worker;
    })
  );
  builder.build();
}
`;

function patchWorkerHelpers(outDir: string) {
    const snippets = path.join(outDir, "snippets");
    let patched = 0;
    if (fs.existsSync(snippets)) {
        for (const dir of fs.readdirSync(snippets)) {
            const src = path.join(snippets, dir, "src");
            if (!dir.startsWith("wasm-bindgen-rayon-") || !fs.existsSync(src)) {
                continue;
            }
            for (const file of fs.readdirSync(src)) {
                if (/^workerHelpers(\.no-bundler)?\.js$/.test(file)) {
                    fs.writeFileSync(path.join(src, file), PATCHED_WORKER_HELPERS);
                    console.log(`patched ${path.join(dir, "src", file)}`);
                    patched += 1;
                }
            }
        }
    }
    // A threads build that ships the unpatched helper is broken in every bundled host.
    if (featuresFor("web").some((f) => f.startsWith("threads")) && patched === 0) {
        throw new Error("threads build: wasm-bindgen-rayon worker helper not found to patch");
    }
}

function runWasmPack(target: "web" | "nodejs", outDir: string, rustSdkDir: string) {
    const args = [
        "build",
        "--target",
        target,
        "--out-dir",
        outDir,
        "--out-name",
        "psy_prover",
        "--no-pack",
        "--release",
        "--no-opt",
        "--",
        "--locked",
        // Cargo features for the prover, e.g. PSY_PROVER_FEATURES=threads (web only).
        ...featuresFor(target),
    ];
    const result = spawnSync("wasm-pack", args, {
        cwd: rustSdkDir,
        stdio: "inherit",
        env: process.env,
    });

    if (result.status !== 0) {
        throw new Error(`wasm-pack build failed for target "${target}"`);
    }
}

function ensureWasmArtifacts() {
    if (process.env.SKIP_WASM_PACK) {
        console.log("SKIP_WASM_PACK set: re-encoding existing prover WASM, skipping wasm-pack...");
        if (!fs.existsSync(wasmPath)) {
            throw new Error(`SKIP_WASM_PACK set but no wasm artifact found at ${wasmPath}`);
        }
        return;
    }

    console.log("Building prover WASM artifacts via wasm-pack...");

    const rustSdkDir = path.resolve(__dirname, "../../../../../psy-rust-sdk");
    const webOutDir = path.resolve(__dirname);
    const nodeOutDir = path.resolve(__dirname, "../local-prover");

    for (const stalePath of [
        path.join(webOutDir, "psy_prover.js"),
        path.join(webOutDir, "psy_prover.d.ts"),
        path.join(webOutDir, "psy_prover_bg.wasm"),
        path.join(webOutDir, "psy_prover_bg.wasm.d.ts"),
        path.join(nodeOutDir, "psy_prover.js"),
        path.join(nodeOutDir, "psy_prover.d.ts"),
        path.join(nodeOutDir, "psy_prover_bg.wasm"),
        path.join(nodeOutDir, "psy_prover_bg.wasm.d.ts"),
    ]) {
        if (fs.existsSync(stalePath)) {
            fs.rmSync(stalePath, { force: true });
        }
    }

    for (const dir of [webOutDir, nodeOutDir]) {
        fs.rmSync(path.join(dir, "snippets"), { recursive: true, force: true });
    }
    runWasmPack("web", webOutDir, rustSdkDir);
    patchWorkerHelpers(webOutDir);
    runWasmPack("nodejs", nodeOutDir, rustSdkDir);

    const gitignoreTemplate = path.resolve(__dirname, "../../../../../.github/templates/.gitignore.wasm");
    if (fs.existsSync(gitignoreTemplate)) {
        fs.copyFileSync(gitignoreTemplate, path.join(webOutDir, ".gitignore"));
        fs.copyFileSync(gitignoreTemplate, path.join(nodeOutDir, ".gitignore"));
    }

    if (!fs.existsSync(wasmPath)) {
        throw new Error(`Expected wasm artifact at ${wasmPath}, but it was not generated`);
    }
}

ensureWasmArtifacts();

const wasmBuffer = fs.readFileSync(wasmPath);
const base64Chunks = wasmBuffer.toString("base64").match(/.{1,65536}/g) ?? [];
const base64ChunkString = base64Chunks.map((chunk) => `    ${JSON.stringify(chunk)},`).join("\n");

// Generate TypeScript module
const moduleContent = `
// Auto-generated WASM binary data
// DO NOT EDIT MANUALLY

const base64Chunks: string[] = [
${base64ChunkString}
];

function decodeBase64(chunks: string[]): Uint8Array {
    const base64 = chunks.join("");
    const atob = (globalThis as { atob?: (data: string) => string }).atob;

    if (typeof atob === "function") {
        const binary = atob(base64);
        const bytes = new Uint8Array(binary.length);

        for (let i = 0; i < binary.length; i += 1) {
            bytes[i] = binary.charCodeAt(i);
        }

        return bytes;
    }

    const buffer = (globalThis as {
        Buffer?: { from(data: string, encoding: "base64"): Uint8Array };
    }).Buffer;

    if (buffer) {
        return new Uint8Array(buffer.from(base64, "base64"));
    }

    throw new Error("No base64 decoder is available in this environment");
}

export const wasmBinary = decodeBase64(base64Chunks);
`;

// Write to output file
const outputPath = path.join(__dirname, './wasm-binary.ts');
fs.writeFileSync(outputPath, moduleContent);

// The raw module too, for hosts that load it as a file and compile it once (setWasmModule).
const distDir = path.resolve(__dirname, "../../dist/local-web-prover");
fs.mkdirSync(distDir, { recursive: true });
fs.copyFileSync(wasmPath, path.join(distDir, "psy_prover_bg.wasm"));

console.log('WASM binary module generated successfully!');
console.log(`Size: ${wasmBuffer.length} bytes`);
